// Keys known at a path like ['services', 'web', 'healthcheck'], or null when anything goes.
export function keysAt(path) {
  if (!path.length) return TOP;
  if (path[0] === 'services' && path.length === 2) return SERVICE;
  const pattern = path.map((p, i) => (i % 2 === 1 && ['services', 'networks', 'volumes', 'configs', 'secrets'].includes(path[i - 1]) ? '*' : p));
  // depends_on.<svc> and networks.<net> inside a service are also free-form names.
  if (pattern[0] === 'services' && pattern.length >= 4 && ['depends_on', 'networks'].includes(pattern[2])) pattern[3] = '*';
  return NESTED[pattern.join('.')] || null;
}
